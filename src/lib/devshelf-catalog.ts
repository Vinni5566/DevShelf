export type SortOrder = "curated" | "az" | "za";

export function filterCatalog(
  items: Technology[],
  query: string,
  category: ShelfCategory | "All",
  sortOrder: SortOrder = "curated",
): Technology[] {
  const needle = query.trim().toLocaleLowerCase();
  const matched = items.filter((item) => {
    const matchesCategory = category === "All" || item.category === category;
    if (!matchesCategory) return false;
    if (!needle) return true;
    const searchable = [item.name, item.category, item.description, item.catalogNo, ...item.tags]
      .join(" ")
      .toLocaleLowerCase();
    return searchable.includes(needle);
  });

  if (sortOrder === "az") {
    return [...matched].sort((a, b) => a.name.localeCompare(b.name));
  }
  if (sortOrder === "za") {
    return [...matched].sort((a, b) => b.name.localeCompare(a.name));
  }
  return matched;
}

export function getCollectionForCategory(category: ShelfCategory): CollectionMeta {
  return collections.find((c) => c.category === category) ?? collections[0]!;
}
